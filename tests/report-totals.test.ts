import { describe, it, expect } from 'vitest';
import { reportTotals } from '@/lib/report-totals';

describe('صف الإجمالي في التقارير', () => {
  it('يجمع الأرقام والأوقات ويترك التعريفات', () => {
    const t = reportTotals(['التاريخ', 'الموظف', 'تأخير (د)', 'ساعات العمل', 'الصافي (د.ك)'], [
      ['2026-11-01', 'A', 10, '8:30', '100.500'],
      ['2026-11-02', 'B', '—', '7:45', '50.250'],
    ]);
    expect(t).toEqual(['الإجمالي (2)', '', 10, '16:15', '150.750']);
  });
  it('لا صف إجمالي لتقرير بلا أرقام', () => {
    expect(reportTotals(['الموظف', 'الحالة'], [['A', 'حاضر']])).toBeNull();
  });
});

describe('كارت الدوام', () => {
  it('يجمع ساعات الوردية ولا يجمع عمود الوردية', () => {
    const t = reportTotals(['التاريخ', 'الوردية', 'ساعات الوردية'], [['2026-11-01', '08:00 - 16:00', '8:00'], ['2026-11-02', '08:00 - 16:00', '8:00']]);
    expect(t).toEqual(['الإجمالي (2)', '', '16:00']);
  });
});
